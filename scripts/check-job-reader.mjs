import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {DEFAULTS,canonical,validateJob,filterJob,filename,safeUrl} from '../resume/generator/job-core.mjs';
import {apiEndpoint} from '../resume/generator/job-api.mjs';
import {makeZip} from '../resume/generator/zip.mjs';
import {selectWording,composePdf} from '../resume/generator/engine.mjs';
const now=Date.parse('2026-11-05T12:00:00Z');
const job={url:'https://www.linkedin.com/jobs/view/mechanical-intern-12345678/?trk=search',title:'Mechanical Engineering Intern',company:'Example / Engineering',location:'Newark, NJ',description:'Use SolidWorks and CAD to design mechanisms, build prototypes and document the results with an engineering team.',datePosted:'2026-11-02'};
assert.equal(canonical(job.url),'https://www.linkedin.com/jobs/view/12345678/');
assert.equal(filterJob(job,DEFAULTS,now).status,'ready');
assert.equal(filterJob({...job,location:'Pittsburgh, PA'},DEFAULTS,now).status,'ready');
assert.equal(filterJob({...job,location:'Remote — United States'},DEFAULTS,now).status,'ready');
assert.equal(filterJob({...job,location:'Remote'},DEFAULTS,now).status,'review');
assert.equal(filterJob({...job,location:'Remote — Canada'},DEFAULTS,now).status,'skipped');
assert.equal(filterJob({...job,location:'Remote — United States'},{...DEFAULTS,remote:false},now).status,'skipped');
assert.equal(filterJob({...job,location:'Austin, TX'},DEFAULTS,now).status,'skipped');
assert.equal(filterJob({...job,title:'Senior Mechanical Engineer'},DEFAULTS,now).status,'skipped');
assert.equal(filterJob({...job,datePosted:''},DEFAULTS,now).status,'ready');
assert.equal(filterJob({...job,datePosted:''},{...DEFAULTS,days:30},now).status,'review');
assert.equal(filterJob({...job,datePosted:'2025-01-01'},{...DEFAULTS,days:30},now).status,'skipped');
assert.equal(filterJob(job,{...DEFAULTS,companies:'Example'},now).status,'skipped');
assert.equal(filterJob(job,{...DEFAULTS,terms:'prototypes'},now).status,'skipped');
assert.equal(filterJob({...job,title:'CAD Co-op'},DEFAULTS,now).status,'ready');
assert.equal(filterJob({...job,title:'Marketing Intern'},DEFAULTS,now).status,'skipped');
assert(!safeUrl('http://localhost/a'));assert(!safeUrl('https://192.168.1.1/a'));assert(!safeUrl('javascript:alert(1)'));assert(!safeUrl('https://user:secret@example.com/job'));
assert.throws(()=>validateJob({...job,description:'short'}));
assert(!filename(job).includes('/'));assert(filename(job).endsWith('.pdf'));assert.notEqual(filename(job),filename({...job,url:job.url+'different'}));
assert(!apiEndpoint('https://evil.com/jobs/1'));assert(!apiEndpoint('https://job-boards.greenhouse.io.evil.com/x/jobs/1'));assert(!apiEndpoint('https://job-boards.greenhouse.io/x/jobs/%2e%2e'));
assert.equal(apiEndpoint('https://job-boards.greenhouse.io/company/jobs/123').url,'https://boards-api.greenhouse.io/v1/boards/company/jobs/123');
assert.equal(apiEndpoint('https://jobs.lever.co/company/abc-def').url,'https://api.lever.co/v0/postings/company/abc-def?mode=json');
assert.equal(canonical('https://job-boards.greenhouse.io/x/jobs/1?gh_src=abc'),canonical('https://job-boards.greenhouse.io/x/jobs/1/'));
assert.notEqual(canonical('https://www.agilityrobotics.com/about/job-post?gh_jid=1'),canonical('https://www.agilityrobotics.com/about/job-post?gh_jid=2'));
const require=createRequire(import.meta.url),{PDFDocument}=require('../resume/generator/pdf-lib.min.js');
const root=new URL('../resume/generator/assets/',import.meta.url),manifest=JSON.parse(await readFile(new URL('manifest.json',root)));
const index=JSON.parse(await readFile(new URL('../data/jobs.json',import.meta.url)));
assert.equal(new Set(index.jobs.map(j=>j.url)).size,index.jobs.length);
const matches=index.jobs.filter(j=>filterJob(j,DEFAULTS).status==='ready');assert(matches.length>=2,'Need two actual regional postings for end-to-end PDF validation');
const files=[];
for(const posting of matches.slice(0,2)){
 const selected=selectWording(manifest,posting.description),data=await composePdf(PDFDocument,selected,file=>readFile(new URL(file,root)));
 const pdf=await PDFDocument.load(data);assert.equal(pdf.getPageCount(),1);assert.equal(pdf.getPages()[0].node.Annots().size(),4);
 files.push({name:filename(posting),data});
}
files.push({name:'job-report.json',data:JSON.stringify(matches.slice(0,2).map(({title,company,url})=>({title,company,url})))});
const archive=makeZip(files),view=new DataView(archive.buffer);
assert.equal(view.getUint32(0,true),0x04034b50);assert.equal(view.getUint32(archive.length-22,true),0x06054b50);assert.equal(view.getUint16(archive.length-12,true),3);
assert.throws(()=>makeZip([{name:'../outside.pdf',data:new Uint8Array()}]));
const folder=new URL('../../tmp/job-reader-test/',import.meta.url);await mkdir(folder,{recursive:true});await writeFile(new URL('real-jobs.zip',folder),archive);
console.log(`PASS: filters, safe imports, deduplication, and ZIP with two one-page PDFs generated from ${matches.length} actual regional matches.`);
